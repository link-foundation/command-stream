/** Translate a shell program to an executable module without changing shell semantics. */
export function fy(
  source,
  { shell = 'sh', name = 'translated.sh', module = 'command-stream' } = {}
) {
  if (typeof source !== 'string' || source.includes('\0')) {
    throw new TypeError('Shell source must be a string without NUL');
  }
  const data = JSON.stringify(source);
  return `#!/usr/bin/env node\n// Generated by $fy. Shell syntax remains interpreted by ${JSON.stringify(shell)}.\nimport { command } from ${JSON.stringify(module)};\nconst source = ${data};\nconst result = await command(${JSON.stringify(shell)}, '-c', source, ${JSON.stringify(name)}, ...process.argv.slice(2))\n  .with({ mirror: true, capture: false, stdin: 'inherit' }).run();\nprocess.exitCode = result.code;\n`;
}
